# ---- no keys on public boxes (infra-m1 §4.1, M1 checklist) ------------------------------
check_no_keys() {
  case "${ROLE}" in
    seed | rpc)
      local found
      # -xdev per starting point: the root disk and the data volume.
      # sed -n 1,5p, not head -5: it reads to EOF, so find is never SIGPIPEd
      # into a silent set -e abort (pipefail) before the die below.
      found="$(find / "${DATA}" -xdev \( -name 'keystore*.json' -o -name 'miner.json' -o -name '*.keystore' \) \
        -not -path '/var/lib/docker/*' 2>/dev/null | sed -n 1,5p)"
      [[ -z "${found}" ]] || die "signing key material on a public ${ROLE} box: ${found}"
      [[ ! -d "${DATA}/faucet" && ! -d "${DATA}/keeper" && ! -d "${DATA}/sealer" ]] ||
        die "faucet/keeper/sealer state on a public ${ROLE} box"
      log "no-keys check passed (only the p2p node key and SSH host keys)"
      ;;
  esac
}

# --render: the files this host would get, written under $RENDER, using
# the same text functions as the real setup. Nothing is installed or run.
render_host() {
  install -d "${ETC}" "${UNIT_DIR}" "${SYSCTL_DIR}"
  swap_sysctl_text >"${SYSCTL_DIR}/${SWAP_SYSCTL_FILE}"
  log "$(swap_plan)"
  write_zebrad_files "$(zebra_ref)"
  cp "${HERE}/systemd/zebrad.service" "${HERE}/systemd/sova-health.service" \
    "${HERE}/systemd/sova-health.timer" "${UNIT_DIR}/"
  health_env_text >"${ETC}/host.env"
  if has_node; then
    local mode_lines="SOVA_FOLLOW_ONLY=1" rpc_profile=public
    if [[ "${ROLE}" == keeper ]]; then
      # The real value comes from `sova-miner init` on the host.
      mode_lines="$(keeper_mode_lines "0x<keeper-evm-from-sova-miner-init>")"
      rpc_profile=local
    fi
    node_env_text "${mode_lines}" "${rpc_profile}" >"${ETC}/sova-node.env"
    cp "${HERE}/systemd/sova-node.service" "${UNIT_DIR}/"
    [[ -z "${SOVA_EPOCH_BASE}" ]] || echo "${SOVA_EPOCH_BASE}" >"${ETC}/epoch-base-pinned"
  fi
  if [[ "${ROLE}" == faucet ]]; then
    faucet_toml_text >"${ETC}/faucet.toml"
    cp "${HERE}/systemd/sova-faucet.service" "${UNIT_DIR}/"
  fi
  if has_relayer; then
    # The key file is made on the host (keygen.mjs), never rendered.
    checkout_relayer_env_text >"${ETC}/checkout-relayer.env"
    cp "${HERE}/systemd/sova-checkout-relayer.service" "${UNIT_DIR}/"
  fi
  if [[ "${ROLE}" == keeper ]]; then
    keeper_env_text >"${ETC}/keeper.env"
    cp "${HERE}/systemd/sova-keeper.service" "${UNIT_DIR}/"
  fi
  has_tunnel && cp "${HERE}/systemd/cloudflared.service" "${UNIT_DIR}/"
  log "rendered into ${RENDER}"
}

if [[ -n "${RENDER}" ]]; then
  render_host
  exit 0
fi

