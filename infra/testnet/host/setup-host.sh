setup_zebrad
install_binaries
[[ "${ROLE}" == keeper ]] && setup_keeper
has_node && setup_node
[[ "${ROLE}" == faucet ]] && setup_faucet
has_relayer && setup_checkout_relayer
has_tunnel && setup_cloudflared
setup_health
check_no_keys
out release "${SOVA_RELEASE_TAG}"
log "done"
