# The genesis hash this host's node boots, from the installed binary itself
# (`sova genesis-hash`: the chainspec for SOVA_CHAIN and SOVA_SIP7, with
# SIP-7's ZcashBlocks predeploy; nothing is started). deploy.sh records it
# as out/servers/<name>.genesis_hash and bootnodes.sh publishes it, so the
# hash is never hard-coded in the kit. A release older than the subcommand
# would ignore the argument and start a node, so it is only run when the
# binary carries the subcommand's usage text; env -i keeps every other
# SOVA_* setting away from it.
node_genesis_hash() {
  local bin=/usr/local/bin/sova hash
  if ! grep -aq 'sova genesis-hash' "${bin}"; then
    log "WARNING: sova ${SOVA_RELEASE_TAG} has no 'genesis-hash' subcommand: genesis hash not recorded (bootnodes.sh refuses to publish without it)"
    return 0
  fi
  hash="$(timeout 60 env -i SOVA_CHAIN=sova-testnet SOVA_SIP7="${SOVA_SIP7}" "${bin}" genesis-hash)" ||
    die "sova genesis-hash failed"
  [[ "${hash}" =~ ^0x[0-9a-f]{64}$ ]] || die "sova genesis-hash printed '${hash}', not a hash"
  log "genesis hash (SIP-7 $([[ "${SOVA_SIP7}" == 1 ]] && echo on || echo off)): ${hash}"
  out genesis_hash "${hash}"
  out genesis_sip7 "${SOVA_SIP7}"
}

setup_node() {
  node_key_and_enode

  local mode_lines rpc_profile=public
  if [[ "${ROLE}" == keeper ]]; then
    # Mine mode: seals its own burns' epochs, and null blocks (SIP-6
    # §2.4; rewardless cadence blocks with SIP-6 off) for burn-less
    # epochs, so the chain has a producer on day 1. It is an ordinary
    # sealer with no privilege (D8). With SIP-6 it signs as the keeper's
    # miner key and journals under SOVA_DATADIR (persistent).
    local evm
    evm="$(keeper_evm_address)"
    mode_lines="$(keeper_mode_lines "${evm}")"
    rpc_profile=local
  else
    mode_lines="SOVA_FOLLOW_ONLY=1"
  fi
  local changed=0
  if [[ "${ROLE}" == keeper && "${SOVA_SIP6}" == 1 ]]; then
    install_sealer_key
    [[ ${SEALER_KEY_CHANGED} == 0 ]] || changed=1
  fi
  node_env_text "${mode_lines}" "${rpc_profile}" >"${ETC}/sova-node.env.new"
  if ! cmp -s "${ETC}/sova-node.env.new" "${ETC}/sova-node.env"; then
    mv "${ETC}/sova-node.env.new" "${ETC}/sova-node.env"
    changed=1
  else
    rm -f "${ETC}/sova-node.env.new"
  fi
  chmod 0644 "${ETC}/sova-node.env"
  node_genesis_hash
  install -m 0644 "${HERE}/systemd/sova-node.service" "${UNIT_DIR}/sova-node.service"
  systemctl daemon-reload
  systemctl enable sova-node >/dev/null 2>&1
  if [[ -z "${SOVA_EPOCH_BASE}" ]]; then
    rm -f "${ETC}/epoch-base-pinned"
    systemctl stop sova-node 2>/dev/null || true
    log "sova-node installed, NOT started: SOVA_EPOCH_BASE is not pinned yet (runbook: Pin B)"
    return 0
  fi
  echo "${SOVA_EPOCH_BASE}" >"${ETC}/epoch-base-pinned"
  # Peer ban length (reth.toml [peers] ban_duration, reth default 12 h): one
  # failed handshake bans the remote IP, so behind a shared VPN exit or
  # carrier NAT one misconfigured node locks everyone there out of the seeds.
  # 1 h (Rob, 2026-09-26). reth writes reth.toml on its first start, so a new
  # host picks this up on its second deploy.
  local toml="${DATA}/node/reth.toml" ban="${PEER_BAN_DURATION:-1h}"
  if [[ -f "${toml}" ]] && ! grep -q "^ban_duration = \"${ban}\"$" "${toml}"; then
    sed -i "s/^ban_duration = \".*\"$/ban_duration = \"${ban}\"/" "${toml}"
    changed=1
    log "reth.toml: peer ban_duration ${ban}"
  fi
  if keeper_paused; then
    # Configured above; started by keeper-resume (with this config).
    log "sova-node NOT started or restarted: the keeper is paused (since $(paused_since), ${KEEPER_PAUSED_FILE}); ./deploy.sh keeper-resume starts it"
    return 0
  fi
  local bin_changed=0
  [[ "$(readlink /usr/local/bin/sova)" != "$(cat "${ETC}/.sova-node.bin" 2>/dev/null)" ]] && bin_changed=1
  if [[ ${changed} == 1 || ${bin_changed} == 1 ]] || ! systemctl is-active --quiet sova-node; then
    systemctl restart sova-node
    readlink /usr/local/bin/sova >"${ETC}/.sova-node.bin"
    log "sova-node (re)started (epoch base ${SOVA_EPOCH_BASE}, ${SOVA_EMISSION_SCHEDULE}, SIP-6 $([[ "${SOVA_SIP6}" == 1 ]] && echo on || echo off), SIP-7 $([[ "${SOVA_SIP7}" == 1 ]] && echo on || echo off))"
  else
    log "sova-node unchanged and running"
  fi
}

