#!/usr/bin/env bash
# infra/testnet/host/setup-host.sh -- configure one M1 testnet host for its
# role. Run as root by deploy.sh (never by hand on a laptop). Idempotent:
# re-running converges, and is how binaries are upgraded (new tag in
# host.env) and how the epoch base / bootnodes are rolled out.
#
#   setup-host.sh <host.env>               full setup
#   setup-host.sh <host.env> --enode-only  node key + enode only
#   setup-host.sh <host.env> --zebra-only  zebrad only (deploy.sh --zebra-only):
#                                          pull, write zebrad.env/.toml and the
#                                          health env, restart zebrad if they
#                                          changed (muted, then the readiness
#                                          wait); nothing else is touched or
#                                          restarted
#   setup-host.sh <host.env> --render DIR  write the files this host would
#                                          get (/etc/sova/*, units) under
#                                          DIR and stop: no root, no
#                                          network, runs on a laptop
#                                          (deploy.sh render uses it)
#
# host.env (generated by deploy.sh, nothing secret) sets ROLE and the
# config.env values below. Roles:
#   seed   zebrad (inbound 18233) + sova-node follow-only, P2P inbound
#   rpc    zebrad + sova-node follow-only (public RPC profile) + cloudflared
#   faucet zebrad + sova-faucet (own hot key) + cloudflared; with
#          CHECKOUT_RELAYER=1 also sova-checkout-relayer (the Ashwings ZEC
#          checkout's public relayer: Node, its own hot key, loopback only)
#   keeper zebrad + sova-node in MINE mode (seals, incl. null blocks;
#          with SOVA_SIP6=1 it signs as the keeper's miner key)
#          + sova-keeper burner (installed, not started)
# Every role: a SWAP_GB (default 4; 0 = none) /swapfile, vm.swappiness=10,
# and the health timer (host/health.sh).
#
# SOVA_SIP6=1 (the default): every node requires SIP-6 sealed or null
# blocks, and the keeper's node signs with a 0600 copy of the keeper's
# sova-miner keystore owned by the node's user (sova), at
# /var/lib/sova/sealer/keystore.json. Its seal journal lives under the
# persistent SOVA_DATADIR (/var/lib/sova/node/seal-journal/<address>).
#
# SOVA_SIP7=1 (the default): every node runs SIP-7 (Zcash pool state) and
# boots the genesis with the ZcashBlocks predeploy at 0x...5A01, a
# different genesis hash from SIP-7 off. Nodes with different values do
# not peer (fork ID), so every node renders the same one.
#
# Every zebrad restart (either mode) mutes this host's Telegram alerts for
# ZEBRA_RESTART_MUTE_MIN (15; host/maint.sh mute) and then waits until
# zebrad is ready again (host/zebra-ready.sh: RPC, image, NU7 height, state
# format upgrade, caught up), up to ZEBRA_READY_TIMEOUT_MIN (15; 0 = don't
# wait). Not ready: this script fails, and so does deploy.sh.
#
# The keeper pause (host/maint.sh keeper-pause, /etc/sova/.keeper-paused):
# while it is on, sova-node and sova-keeper are configured but never
# started or restarted here.
#
# Lines starting "KIT-OUT " are machine-read by deploy.sh (enode, faucet
# t-addr, keeper addresses, zebrad readiness timings: all public).
set -euo pipefail

ENV_FILE="${1:?usage: setup-host.sh <host.env>}"
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=/dev/null
source "${ENV_FILE}"

: "${ROLE:?}" "${PUBLIC_IPV4:?}" "${SOVA_RELEASE_TAG:?}" "${SOVA_RELEASE_REPO:?}"
: "${ZEBRA_IMAGE:?}" "${SOVA_P2P_PORT:?}" "${ZEBRA_P2P_PORT:?}" "${ZEBRA_RPC_PORT:?}"
: "${SOVA_HTTP_PORT:?}" "${SOVA_AUTH_PORT:?}" "${FAUCET_PORT:?}"
SOVA_EPOCH_BASE="${SOVA_EPOCH_BASE:-}"
SOVA_BOOTNODES="${SOVA_BOOTNODES:-}"
SOVA_EMISSION_SCHEDULE="${SOVA_EMISSION_SCHEDULE:-flat}"
SOVA_SIP6="${SOVA_SIP6:-1}"
SOVA_SIP7="${SOVA_SIP7:-1}"
BUILD_FROM_SOURCE="${BUILD_FROM_SOURCE:-0}"
CHECKOUT_RELAYER="${CHECKOUT_RELAYER:-0}"
SWAP_GB="${SWAP_GB:-4}"

DATA=/var/lib/sova
ETC=/etc/sova
# SIP-6: the keeper node's sealing key, a copy of the keeper's miner
# keystore readable only by the node's user (sova-node.service User=sova).
SEALER_KEYSTORE="${DATA}/sealer/keystore.json"
UNIT_DIR=/etc/systemd/system
SYSCTL_DIR=/etc/sysctl.d
RENDER=""
if [[ "${2:-}" == --render ]]; then
  RENDER="${3:?--render needs a directory}"
  ETC="${RENDER}/etc/sova"
  UNIT_DIR="${RENDER}/etc/systemd/system"
  SYSCTL_DIR="${RENDER}/etc/sysctl.d"
fi
# The keeper pause marker (host/maint.sh keeper-pause).
KEEPER_PAUSED_FILE="${ETC}/.keeper-paused"
PLATFORM=linux-x86_64
ASSET="sova-box-bin-${PLATFORM}.tar.gz"

log() { printf '[setup-host %s] %s\n' "${ROLE}" "$*"; }
die() {
  printf '[setup-host %s] error: %s\n' "${ROLE}" "$*" >&2
  exit 1
}
# To stderr, so it survives command substitution; deploy.sh reads 2>&1.
out() { printf 'KIT-OUT %s %s\n' "$1" "$2" >&2; }

if [[ -z "${RENDER}" ]]; then
  [[ "$(id -u)" == 0 ]] || die "run as root"
  [[ "$(uname -m)" == x86_64 ]] || die "x86_64 only (the release ships ${PLATFORM})"
  # shellcheck source=/dev/null
  . /etc/os-release
  [[ "${ID}" == ubuntu ]] || die "Ubuntu expected, got ${ID}"
fi
case "${ROLE}" in seed | rpc | faucet | keeper) ;; *) die "unknown ROLE ${ROLE}" ;; esac
[[ -z "${SOVA_EPOCH_BASE}" || "${SOVA_EPOCH_BASE}" =~ ^[1-9][0-9]*$ ]] || die "SOVA_EPOCH_BASE must be a positive integer"
case "${SOVA_EMISSION_SCHEDULE}" in sip3 | flat) ;; *) die "SOVA_EMISSION_SCHEDULE must be sip3 or flat" ;; esac
case "${SOVA_SIP6}" in 0 | 1) ;; *) die "SOVA_SIP6 must be 0 or 1" ;; esac
case "${SOVA_SIP7}" in 0 | 1) ;; *) die "SOVA_SIP7 must be 0 or 1" ;; esac
case "${CHECKOUT_RELAYER}" in 0 | 1) ;; *) die "CHECKOUT_RELAYER must be 0 or 1" ;; esac
if ! [[ "${SWAP_GB}" =~ ^[0-9]+$ ]] || ((SWAP_GB > 64)); then die "SWAP_GB must be 0..64 (GB; 0 = no swapfile)"; fi

has_node() { [[ "${ROLE}" == seed || "${ROLE}" == rpc || "${ROLE}" == keeper ]]; }
has_tunnel() { [[ "${ROLE}" == rpc || "${ROLE}" == faucet ]]; }
has_relayer() { [[ "${ROLE}" == faucet && "${CHECKOUT_RELAYER}" == 1 ]]; }
keeper_paused() { [[ "${ROLE}" == keeper && -f "${KEEPER_PAUSED_FILE}" ]]; }
paused_since() { sed -n 's/^since=//p' "${KEEPER_PAUSED_FILE}" 2>/dev/null; }
if has_relayer; then
  : "${CHECKOUT_RELAYER_PORT:?}" "${CHECKOUT_RELAYER_SOVA_RPC:?}" "${CHECKOUT_RELAYER_CORS_ORIGIN:?}" "${CHECKOUT_RELAYER_NODE_MAJOR:?}"
fi

# ---- data volume ----------------------------------------------------------------
mount_volume() {
  local devs=() d uuid
  for d in /dev/disk/by-id/scsi-0HC_Volume_*; do [[ -e "${d}" ]] && devs+=("${d}"); done
  mkdir -p "${DATA}"
  if [[ ${#devs[@]} -eq 0 ]]; then
    # Also the normal case on an (optional) byo host, e.g. an AWS keeper
    # with one 40 GB gp3 root volume.
    log "no Hetzner volume attached; state lives on the root disk"
    return 0
  fi
  [[ ${#devs[@]} -eq 1 ]] || die "expected one attached volume, found ${#devs[@]}"
  uuid="$(blkid -s UUID -o value "${devs[0]}")" || die "volume ${devs[0]} has no filesystem (provision.sh formats it ext4)"
  if ! grep -q "UUID=${uuid}" /etc/fstab; then
    echo "UUID=${uuid} ${DATA} ext4 defaults,discard,nofail 0 2" >>/etc/fstab
  fi
  mountpoint -q "${DATA}" || mount "${DATA}"
  log "data volume ${devs[0]} mounted at ${DATA}"
}

# ---- swap ---------------------------------------------------------------------------------
# A SWAP_GB swapfile on every host (0 = the kit manages none), and
# vm.swappiness=10 so the kernel drops page cache before it swaps out the
# nodes' working sets: swap is a cushion against running out of memory, not
# extra RAM. 2026-09-27: reth's state cache filled the 4 GB hosts, which had
# no swap; zebrad stopped answering, the chain stalled ~20 min and the
# public RPC host thrashed. An active /swapfile (e.g. one made by hand) is
# left as it is, whatever its size.
SWAPFILE=/swapfile
SWAP_SYSCTL_FILE=60-sova-swap.conf

swap_sysctl_text() {
  cat <<EOF
# Written by setup-host.sh; re-run deploy.sh to change it. Drop page cache
# before swapping out the nodes' working sets (swap is a cushion).
vm.swappiness=10
EOF
}

swap_fstab_line() { printf '%s none swap sw 0 0\n' "${SWAPFILE}"; }

# The swap line for the render log: what setup_swap would do.
swap_plan() {
  if [[ "${SWAP_GB}" == 0 ]]; then
    echo "swap: SWAP_GB=0, no swapfile managed; vm.swappiness=10"
  else
    echo "swap: ${SWAPFILE} ${SWAP_GB} GB if absent (fallocate, chmod 600, mkswap, swapon; fstab '$(swap_fstab_line)'); vm.swappiness=10"
  fi
}

# Whether $SWAPFILE is an active swap area now.
swapfile_active() {
  local active
  active="$(swapon --show=NAME --noheadings 2>/dev/null || true)"
  grep -qxF "${SWAPFILE}" <<<"${active}"
}

setup_swap() {
  local f="${SWAPFILE}" conf="${SYSCTL_DIR}/${SWAP_SYSCTL_FILE}"
  # swappiness always: harmless without swap, and useful with a host's own.
  install -d -m 0755 "${SYSCTL_DIR}"
  swap_sysctl_text >"${conf}.new"
  if cmp -s "${conf}.new" "${conf}"; then
    rm -f "${conf}.new"
  else
    mv "${conf}.new" "${conf}"
    chmod 0644 "${conf}"
    log "sysctl: vm.swappiness=10 (${conf})"
  fi
  sysctl -q -p "${conf}" >/dev/null || log "WARNING: sysctl could not load ${conf} (vm.swappiness is $(cat /proc/sys/vm/swappiness 2>/dev/null))"
  if [[ "${SWAP_GB}" == 0 ]]; then
    log "swap: SWAP_GB=0, no swapfile managed (swap now: $(free -m | awk '/^Swap:/ { print $2 " MB" }'))"
    return 0
  fi
  if swapfile_active; then
    log "swap: ${f} already active ($(swapon --show=NAME,SIZE --noheadings | awk -v f="${f}" '$1 == f { print $2 }')), left as is"
  else
    if [[ -e "${f}" ]]; then
      chmod 0600 "${f}"
      if swapon "${f}" 2>/dev/null; then
        log "swap: ${f} existed but was off: turned it on"
      else
        # Not a swap area (e.g. a create that died before mkswap): redo it.
        rm -f "${f}"
        log "swap: ${f} existed but was not a usable swap area: re-creating it"
      fi
    fi
    if ! swapfile_active; then
      local avail_mb need_mb=$((SWAP_GB * 1024 + 2048))
      avail_mb="$(df --output=avail -m / | tail -1 | tr -dc '0-9')"
      if [[ -z "${avail_mb}" ]] || ((avail_mb < need_mb)); then
        log "WARNING: swap: only ${avail_mb:-?} MB free on /, need ${need_mb} (SWAP_GB=${SWAP_GB} + 2 GB): NO swapfile made; lower SWAP_GB or free the disk"
        return 0
      fi
      if ! { fallocate -l "${SWAP_GB}G" "${f}" 2>/dev/null ||
        dd if=/dev/zero of="${f}" bs=1M count=$((SWAP_GB * 1024)) status=none; }; then
        rm -f "${f}"
        die "swap: could not allocate ${f} (${SWAP_GB} GB)"
      fi
      chmod 0600 "${f}"
      mkswap "${f}" >/dev/null || { rm -f "${f}"; die "swap: mkswap ${f} failed"; }
      swapon "${f}" || die "swap: swapon ${f} failed"
      log "swap: created ${f} (${SWAP_GB} GB) and turned it on"
    fi
  fi
  if grep -qE "^[[:space:]]*${f}[[:space:]]" /etc/fstab; then
    log "swap: ${f} already in /etc/fstab"
  else
    swap_fstab_line >>/etc/fstab
    log "swap: added '$(swap_fstab_line)' to /etc/fstab"
  fi
}

# ---- users and directories --------------------------------------------------------
ensure_user() { # name [uid]
  if ! id -u "$1" >/dev/null 2>&1; then
    if [[ -n "${2:-}" ]]; then
      groupadd --system --gid "$2" "$1"
      useradd --system --uid "$2" --gid "$2" --home-dir /nonexistent --shell /usr/sbin/nologin "$1"
    else
      useradd --system --user-group --home-dir /nonexistent --shell /usr/sbin/nologin "$1"
    fi
  fi
}

setup_dirs() {
  # The zfnd/zebra image runs zebrad as uid/gid 10001.
  ensure_user zebra 10001
  install -d -m 0750 -o 10001 -g 10001 "${DATA}/zebrad"
  install -d -m 0755 "${ETC}" /usr/local/lib/sova-infra
  if has_node; then
    ensure_user sova
    install -d -m 0700 -o sova -g sova "${DATA}/node" "${DATA}/node/tmp"
  fi
  if [[ "${ROLE}" == faucet ]]; then
    ensure_user sova-faucet
    install -d -m 0700 -o sova-faucet -g sova-faucet "${DATA}/faucet"
  fi
  if has_relayer; then
    ensure_user sova-checkout
    install -d -m 0700 -o sova-checkout -g sova-checkout "${DATA}/checkout-relayer"
  fi
  if [[ "${ROLE}" == keeper ]]; then
    ensure_user sova-keeper
    install -d -m 0700 -o sova-keeper -g sova-keeper "${DATA}/keeper"
  fi
}

# ---- host firewall (mirrors the Hetzner firewall / a byo host's security group;
# defence in depth) -----------------------------------------------------------------
setup_ufw() {
  ufw default deny incoming >/dev/null
  ufw default allow outgoing >/dev/null
  ufw allow 22/tcp >/dev/null
  if [[ "${ROLE}" == seed ]]; then
    ufw allow "${SOVA_P2P_PORT}/tcp" >/dev/null
    ufw allow "${SOVA_P2P_PORT}/udp" >/dev/null
    ufw allow "${ZEBRA_P2P_PORT}/tcp" >/dev/null
  fi
  ufw --force enable >/dev/null
  log "ufw: $(ufw status | grep -c ALLOW) allow rule(s)"
}

# ---- zebrad -------------------------------------------------------------------------
zebra_ref() {
  local ref="${ZEBRA_IMAGE}"
  [[ -n "${ZEBRA_IMAGE_DIGEST:-}" ]] && ref="${ZEBRA_IMAGE}@${ZEBRA_IMAGE_DIGEST}"
  printf '%s' "${ref}"
}

write_zebrad_files() { # image-ref
  printf 'ZEBRA_IMAGE_REF=%s\n' "$1" >"${ETC}/zebrad.env"
  sed -e "s/@ZEBRA_P2P_PORT@/${ZEBRA_P2P_PORT}/" -e "s/@ZEBRA_RPC_PORT@/${ZEBRA_RPC_PORT}/" \
    "${HERE}/zebrad.toml" >"${ETC}/zebrad.toml"
  chmod 0644 "${ETC}/zebrad.toml"
}

setup_zebrad() {
  local ref
  ref="$(zebra_ref)"
  docker pull -q "${ref}" >/dev/null || die "docker pull ${ref} failed"
  write_zebrad_files "${ref}"
  install -m 0644 "${HERE}/systemd/zebrad.service" "${UNIT_DIR}/zebrad.service"
  systemctl daemon-reload
  systemctl enable zebrad >/dev/null 2>&1
  # Restart only if the image or config changed (a restart costs a
  # RocksDB reopen, not a resync).
  local sum
  sum="$(cat "${ETC}/zebrad.env" "${ETC}/zebrad.toml" | sha256sum | cut -d' ' -f1)"
  if [[ "$(cat "${ETC}/.zebrad.sum" 2>/dev/null)" != "${sum}" ]] || ! systemctl is-active --quiet zebrad; then
    # Where zebrad is before the restart ("<tip> <lag behind the
    # references>", "- 0" when it doesn't answer), for the readiness wait.
    local pre t0 t1 mute="${ZEBRA_RESTART_MUTE_MIN:-15}"
    pre="$(ZEBRA_READY_ENV="${ENV_FILE}" bash "${HERE}/zebra-ready.sh" before)" || pre="- 0"
    # Planned noise (zebrad_down, a short epoch_lag): no Telegram for a while.
    [[ "${mute}" == 0 ]] || bash "${HERE}/maint.sh" mute "${mute}" "zebrad restart (${ref##*/})"
    t0="$(date +%s)"
    systemctl restart zebrad
    t1="$(date +%s)"
    echo "${sum}" >"${ETC}/.zebrad.sum"
    log "zebrad (re)started with ${ref}"
    ZEBRA_READY_ENV="${ENV_FILE}" bash "${HERE}/zebra-ready.sh" wait --since "${t0}" --started "${t1}" \
      --pre-tip "${pre% *}" --pre-lag "${pre#* }" ||
      die "zebrad is not ready after the restart (above); the rollout stops here"
  else
    log "zebrad unchanged and running"
  fi
}

# ---- binaries: tagged GitHub Release, SHA256SUMS verified -------------------------
# Same checks as box/up.sh's fetch_prebuilt_from_release/verify_prebuilt:
# release-level SHA256SUMS over the tarball, release BUILD-INFO names the
# tag and platform, the tarball's own SHA256SUMS over both binaries, and
# the tarball's BUILD-INFO commit equals the release's.
RELEASE_COMMIT=""
install_release_binaries() {
  local dest="/usr/local/lib/sova/${SOVA_RELEASE_TAG}"
  if [[ -x "${dest}/sova" && -x "${dest}/sova-miner" && -s "${dest}/COMMIT" ]]; then
    RELEASE_COMMIT="$(cat "${dest}/COMMIT")"
    log "release ${SOVA_RELEASE_TAG} already installed (${RELEASE_COMMIT:0:12})"
    return 0
  fi
  local tmp base expected actual rel_tag rel_platforms inner_commit inner_platform f
  tmp="$(mktemp -d)"
  base="https://github.com/${SOVA_RELEASE_REPO}/releases/download/${SOVA_RELEASE_TAG}"
  for f in SHA256SUMS BUILD-INFO "${ASSET}"; do
    curl -fsSL --retry 3 -o "${tmp}/${f}" "${base}/${f}" || {
      rm -rf "${tmp}"
      return 1
    }
  done
  expected="$(awk -v n="${ASSET}" '$2 == n || $2 == ("*" n) { print $1; exit }' "${tmp}/SHA256SUMS")"
  actual="$(sha256sum "${tmp}/${ASSET}" | cut -d' ' -f1)"
  [[ -n "${expected}" && "${expected}" == "${actual}" ]] || die "release ${ASSET}: SHA-256 mismatch (SHA256SUMS '${expected:0:12}', got '${actual:0:12}')"
  rel_tag="$(sed -n 's/^tag=//p' "${tmp}/BUILD-INFO")"
  rel_platforms="$(sed -n 's/^platforms=//p' "${tmp}/BUILD-INFO")"
  RELEASE_COMMIT="$(sed -n 's/^commit=//p' "${tmp}/BUILD-INFO")"
  [[ "${rel_tag}" == "${SOVA_RELEASE_TAG}" ]] || die "release BUILD-INFO names tag '${rel_tag}', expected ${SOVA_RELEASE_TAG}"
  [[ " ${rel_platforms} " == *" ${PLATFORM} "* ]] || die "release does not list ${PLATFORM}"
  mkdir -p "${tmp}/x"
  tar -xzf "${tmp}/${ASSET}" -C "${tmp}/x" sova sova-miner SHA256SUMS BUILD-INFO ||
    die "${ASSET} does not unpack to sova, sova-miner, SHA256SUMS, BUILD-INFO"
  # Only the two binaries installed here: from v0.1.20 the tarball's
  # SHA256SUMS also lists sova-rebuild and sova-near-da, not unpacked here.
  if ! grep -Eq '^[0-9a-f]{64}  sova$' "${tmp}/x/SHA256SUMS" ||
    ! grep -Eq '^[0-9a-f]{64}  sova-miner$' "${tmp}/x/SHA256SUMS"; then
    die "tarball SHA256SUMS does not cover sova and sova-miner"
  fi
  (cd "${tmp}/x" && grep -E '^[0-9a-f]{64}  (sova|sova-miner)$' SHA256SUMS | sha256sum -c --quiet -) ||
    die "tarball SHA256SUMS check failed"
  inner_commit="$(sed -n 's/^commit=//p' "${tmp}/x/BUILD-INFO")"
  inner_platform="$(sed -n 's/^platform=//p' "${tmp}/x/BUILD-INFO")"
  [[ "${inner_commit}" == "${RELEASE_COMMIT}" ]] || die "tarball commit ${inner_commit} != release commit ${RELEASE_COMMIT}"
  [[ "${inner_platform}" == "${PLATFORM}" ]] || die "tarball is for ${inner_platform}"
  install -d "${dest}"
  install -m 0755 "${tmp}/x/sova" "${tmp}/x/sova-miner" "${dest}/"
  install -m 0644 "${tmp}/x/SHA256SUMS" "${tmp}/x/BUILD-INFO" "${dest}/"
  echo "${RELEASE_COMMIT}" >"${dest}/COMMIT"
  rm -rf "${tmp}"
  log "installed release ${SOVA_RELEASE_TAG} (${RELEASE_COMMIT:0:12}), SHA256SUMS verified"
}

# Source build (the faucet always; everything with BUILD_FROM_SOURCE=1).
# Checks the tag's commit against the release's when there is one.
SRC=""
ensure_source() {
  [[ -n "${SRC}" ]] && return 0
  apt-get update -qq && apt-get install -y -qq build-essential pkg-config clang >/dev/null
  ensure_user sova-build
  install -d -m 0755 -o sova-build -g sova-build "${DATA}/build"
  local home="${DATA}/build"
  if [[ ! -x "${home}/.cargo/bin/cargo" ]]; then
    sudo -u sova-build HOME="${home}" sh -c \
      'curl -fsSL https://sh.rustup.rs | sh -s -- -y --profile minimal --default-toolchain stable' >/dev/null
  fi
  SRC="${home}/src-${SOVA_RELEASE_TAG}"
  if [[ ! -d "${SRC}/.git" ]]; then
    sudo -u sova-build git clone -q --depth 1 --branch "${SOVA_RELEASE_TAG}" "${SOVA_SOURCE_REPO_URL}" "${SRC}"
  fi
  local head
  head="$(sudo -u sova-build git -C "${SRC}" rev-parse HEAD)"
  if [[ -n "${RELEASE_COMMIT}" && "${head}" != "${RELEASE_COMMIT}" ]]; then
    die "tag ${SOVA_RELEASE_TAG} is ${head} in ${SOVA_SOURCE_REPO_URL}, but the release was built from ${RELEASE_COMMIT}"
  fi
  log "source ${SOVA_RELEASE_TAG} at ${head:0:12}"
}

cargo_build() { # cargo args...
  sudo -u sova-build HOME="${DATA}/build" CARGO_TARGET_DIR="${DATA}/build/target" \
    sh -c 'cd "$0" && "$HOME/.cargo/bin/cargo" build --release --locked "$@"' "${SRC}" "$@"
}

install_binaries() {
  local dest="/usr/local/lib/sova/${SOVA_RELEASE_TAG}"
  if [[ "${BUILD_FROM_SOURCE}" == 1 ]] || ! install_release_binaries; then
    [[ "${BUILD_FROM_SOURCE}" == 1 ]] || log "release download failed; building from source (slow: reth, ~20-40 min)"
    ensure_source
    cargo_build -p sova
    cargo_build -p sova-miner --manifest-path crates/burn-wallet/Cargo.toml
    install -d "${dest}"
    install -m 0755 "${DATA}/build/target/release/sova" "${DATA}/build/target/release/sova-miner" "${dest}/"
    # shellcheck disable=SC2024 # root writes the file; git runs as the build user
    sudo -u sova-build git -C "${SRC}" rev-parse HEAD >"${dest}/COMMIT"
  fi
  if [[ "${ROLE}" == faucet && ! -x "${dest}/sova-faucet" ]]; then
    # Not in the release tarball; the burn-wallet workspace doesn't link
    # reth, so this is a few minutes.
    ensure_source
    cargo_build -p sova-faucet --manifest-path crates/burn-wallet/Cargo.toml
    install -m 0755 "${DATA}/build/target/release/sova-faucet" "${dest}/"
  fi
  local b
  for b in sova sova-miner sova-faucet; do
    [[ -x "${dest}/${b}" ]] && ln -sfn "${dest}/${b}" "/usr/local/bin/${b}"
  done
  echo "${SOVA_RELEASE_TAG}" >"${ETC}/release"
}

# ---- sova node ----------------------------------------------------------------------
node_key_and_enode() {
  local key="${DATA}/node/discovery-secret"
  if [[ ! -s "${key}" ]]; then
    # Pre-generated so the enode is known before the first start, and
    # stable across restarts (SOVA_DATADIR). reth parses exactly 64 hex
    # chars: no trailing newline.
    (umask 077 && openssl rand -hex 32 | tr -d '\n' >"${key}")
    chown sova:sova "${key}"
  fi
  chmod 0600 "${key}"
  local enode
  enode="$(python3 "${HERE}/enode.py" "${key}" "${PUBLIC_IPV4}" "${SOVA_P2P_PORT}")"
  echo "${enode}" >"${ETC}/enode"
  out enode "${enode}"
}

# No SOVA_RPC_CORS here on purpose: every host's RPC binds 127.0.0.1, and
# the only browser-facing path is rpc.<domain> through the edge Worker
# (worker/rpc-firewall.mjs), which answers CORS itself.
